#!/usr/bin/env bash
# Write create_table.sql (DDL for <database>.faces and <database>.people, both with HNSW indexes) and run it.
#
#   ./create_table_doris.sh              # create the database and tables if missing (keeps existing data)
#   ./create_table_doris.sh --recreate   # DROP and re-create both tables (after a schema change)
#   ./create_table_doris.sh --dry-run    # only write create_table.sql
#
# Settings come from .env / the environment (see env.example): VELODB_DATABASE, VELODB_FACES_BUCKETS,
# VELODB_PEOPLE_BUCKETS, VELODB_REPLICATION_NUM. run-load.sh calls this for you.
set -euo pipefail
cd "$(dirname "$0")"
. ./env.sh

DRY_RUN=0; RECREATE=0
case "${1:-}" in
  --dry-run) DRY_RUN=1;;
  --recreate) RECREATE=1;;
  "") ;;
  *) echo "usage: $0 [--dry-run|--recreate]" >&2; exit 2;;
esac
CREATE="CREATE TABLE IF NOT EXISTS"; DROP=""
if [ "$RECREATE" = 1 ]; then
  CREATE="CREATE TABLE"
  DROP="DROP TABLE IF EXISTS ${DATABASE}.faces;
DROP TABLE IF EXISTS ${DATABASE}.people;"
fi

SQL_FILE=create_table.sql
cat > "$SQL_FILE" <<SQL
-- Generated by create_table_doris.sh on $(date -u +'%Y-%m-%dT%H:%M:%SZ')
-- Doris / VeloDB schema for the face-similarity demo (export/ from face-export.py).
-- IMDB-WIKI face photos, embedded with InsightFace ArcFace R50 (buffalo_l, w600k_r50).
--
-- Vector search: the embedding column carries an HNSW ANN index. Vectors are
-- L2-normalized, so inner_product == cosine similarity (1 = identical,
-- >= ~0.4 usually the same person, ~0 unrelated).
-- Hybrid search: the label columns can be used in WHERE alongside the ANN
-- ordering, e.g. gender, birth_year, or label_score_pct >= 35 ("the dataset's
-- name for this photo is trustworthy"). Filter only on columns with an
-- inverted index, or the ANN query falls back to brute force. See sample_query.sql.

CREATE DATABASE IF NOT EXISTS ${DATABASE};

${DROP}

${CREATE} ${DATABASE}.faces (
    face_id      BIGINT        NOT NULL COMMENT 'shard * 100000 + row in the HF dataset',
    name         VARCHAR(512)  NULL     COMMENT 'person the dataset says is in the photo',
    gender       VARCHAR(8)    NULL     COMMENT 'male / female (dataset label)',
    birth_year   INT           NULL,
    photo_year   INT           NULL     COMMENT 'year the photo was taken',
    age          INT           NULL     COMMENT 'age in the photo (photo_year - birth year)',
    source       VARCHAR(8)    NULL     COMMENT 'imdb / wiki',
    img_w        INT           NULL,
    img_h        INT           NULL,
    n_faces      INT           NULL     COMMENT 'faces detected in the photo',
    det_score    FLOAT         NULL     COMMENT 'SCRFD face detection confidence',
    face_px      INT           NULL     COMMENT 'face width in source pixels',
    person_faces INT           NULL     COMMENT 'photos in the dataset carrying this name',
    label_score  FLOAT         NULL     COMMENT 'cosine to the dominant identity of this name; < 0.3 = likely mislabeled',
    label_score_pct INT        NULL     COMMENT 'round(label_score * 100): indexable copy for filters (no inverted index on FLOAT)',
    image        STRING        NULL     COMMENT 'base64 JPEG thumbnail, longest side 160px',
    embedding    ARRAY<FLOAT>  NOT NULL COMMENT 'ArcFace 512-d, L2-normalized',

    INDEX idx_embedding (embedding) USING ANN PROPERTIES (
        "index_type"  = "hnsw",
        "metric_type" = "inner_product",
        "dim"         = "512"
    ),
    INDEX idx_name (name) USING INVERTED PROPERTIES ("parser" = "unicode", "support_phrase" = "true"),
    -- Filter columns need inverted indexes: Doris evaluates an indexed predicate
    -- to a row bitmap and hands it to the HNSW search. A predicate WITHOUT an
    -- index makes the ANN query fall back to brute force over the filtered rows
    -- (profile counter AnnIndexFallbackBruteForceCnt).
    INDEX idx_gender      (gender)      USING INVERTED,
    INDEX idx_source      (source)      USING INVERTED,
    INDEX idx_label_score (label_score_pct) USING INVERTED,
    INDEX idx_birth_year  (birth_year)  USING INVERTED,
    INDEX idx_age         (age)         USING INVERTED,
    INDEX idx_photo_year  (photo_year)  USING INVERTED
)
ENGINE = OLAP
DUPLICATE KEY (face_id)   -- ANN indexes require the duplicate-key model
COMMENT 'IMDB-WIKI celebrity faces with ArcFace embeddings for face similarity search'
DISTRIBUTED BY HASH (face_id) BUCKETS ${VELODB_FACES_BUCKETS}
PROPERTIES ("replication_num" = "${VELODB_REPLICATION_NUM}");

-- One row per person: the centroid ("average face") of the photos that agree
-- with each other under that name (see face-export.py). Ranking identities
-- instead of photos answers "which celebrity does this face look like?".
${CREATE} ${DATABASE}.people (
    name            VARCHAR(512)  NOT NULL,
    gender          VARCHAR(8)    NULL,
    birth_year      INT           NULL,
    photos          INT           NULL COMMENT 'photos carrying this name',
    verified_photos INT           NULL COMMENT 'photos in the centroid (mutually consistent)',
    face_id         BIGINT        NULL COMMENT 'most typical photo -> faces.face_id',
    embedding       ARRAY<FLOAT>  NOT NULL COMMENT 'L2-normalized mean ArcFace vector',

    INDEX idx_embedding (embedding) USING ANN PROPERTIES (
        "index_type"  = "hnsw",
        "metric_type" = "inner_product",
        "dim"         = "512"
    ),
    INDEX idx_gender     (gender)     USING INVERTED,
    INDEX idx_birth_year (birth_year) USING INVERTED
)
ENGINE = OLAP
DUPLICATE KEY (name)
COMMENT 'Per-person centroid face vectors'
DISTRIBUTED BY HASH (name) BUCKETS ${VELODB_PEOPLE_BUCKETS}
PROPERTIES ("replication_num" = "${VELODB_REPLICATION_NUM}");
SQL

echo "wrote $SQL_FILE (${DATABASE}.faces ${VELODB_FACES_BUCKETS} buckets, ${DATABASE}.people ${VELODB_PEOPLE_BUCKETS} buckets, replication ${VELODB_REPLICATION_NUM})"
[ "$DRY_RUN" = 1 ] && exit 0

# mysql 9 client cannot authenticate against Doris (mysql_native_password); use the pymysql helper
# from the project-local venv (created on first run).
PY=$(./ensure-venv.sh)
echo "$( [ "$RECREATE" = 1 ] && echo re-creating || echo creating if missing) ${DATABASE}.faces / ${DATABASE}.people on ${VELODB_HOST}:${VELODB_MYSQL_PORT} ..."
"$PY" doris_sql.py --env "$ENV_FILE" -q "$SQL_FILE"
echo "ok"
