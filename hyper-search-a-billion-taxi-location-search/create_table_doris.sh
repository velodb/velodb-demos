#!/usr/bin/env bash
# Write create_table.sql (DDL for the taxi_ping table) and execute it in Doris.
#
#   ./create_table_doris.sh              # write create_table.sql and run it (DROP + CREATE)
#   ./create_table_doris.sh --dry-run    # only write create_table.sql
#
# Settings come from .env / the environment (see env.example): VELODB_DATABASE, VELODB_TABLE, VELODB_BUCKETS,
# VELODB_REPLICATION_NUM, VELODB_PARTITION_KEEP_DAYS, VELODB_PARTITION_AHEAD_DAYS.
set -euo pipefail
cd "$(dirname "$0")"
. ./env.sh
BUCKETS="$VELODB_BUCKETS"; REPLICATION_NUM="$VELODB_REPLICATION_NUM"
PARTITION_KEEP_DAYS="$VELODB_PARTITION_KEEP_DAYS"; PARTITION_AHEAD_DAYS="$VELODB_PARTITION_AHEAD_DAYS"

DRY_RUN=0
[ "${1:-}" = "--dry-run" ] && DRY_RUN=1

SQL_FILE=create_table.sql
cat > "$SQL_FILE" <<SQL
-- Generated by create_table_doris.sh on $(date -u +'%Y-%m-%dT%H:%M:%SZ')
-- 1B-row taxi ping table: partition pruning (ts), bucket pruning (geohash6), inverted indexes.

CREATE DATABASE IF NOT EXISTS ${DATABASE};

DROP TABLE IF EXISTS ${DATABASE}.${TABLE};

CREATE TABLE ${DATABASE}.${TABLE} (
  ts         DATETIME(3)  NOT NULL COMMENT 'ping time (= load BASE + offset_ms)',
  taxi_id    INT          NOT NULL,
  geohash6   VARCHAR(6)   NOT NULL COMMENT '~1.2km x 0.6km cell; distribution key',
  geohash8   VARCHAR(8)   NOT NULL COMMENT '~38m x 19m cell; geohash6 is its prefix',
  lat        DOUBLE       NOT NULL,
  lon        DOUBLE       NOT NULL,
  status     VARCHAR(16)  NOT NULL COMMENT 'AVAILABLE | ON_CALL | HIRED | OFFLINE',
  speed_kmh  SMALLINT     NOT NULL,
  heading    SMALLINT     NOT NULL COMMENT '0..359 degrees',
  plate      VARCHAR(12)  NOT NULL,
  company    VARCHAR(32)  NOT NULL,
  INDEX idx_geohash6 (geohash6) USING INVERTED,
  INDEX idx_geohash8 (geohash8) USING INVERTED,
  INDEX idx_taxi_id  (taxi_id)  USING INVERTED,
  INDEX idx_status   (status)   USING INVERTED,
  INDEX idx_plate    (plate)    USING INVERTED,
  INDEX idx_company  (company)  USING INVERTED
)
ENGINE = OLAP
DUPLICATE KEY(ts, taxi_id)
COMMENT 'Taxi GPS pings; history is loaded from S3 with ts relative to load time'
AUTO PARTITION BY RANGE (date_trunc(ts, 'day')) ()
DISTRIBUTED BY HASH(geohash6) BUCKETS ${BUCKETS}
PROPERTIES (
  "replication_num" = "${REPLICATION_NUM}",
  "compression" = "ZSTD",
  -- auto partition creates day partitions as data arrives; dynamic partition handles retention:
  -- drop partitions older than ${PARTITION_KEEP_DAYS} days, pre-create ${PARTITION_AHEAD_DAYS} days ahead.
  "dynamic_partition.enable" = "true",
  "dynamic_partition.time_unit" = "DAY",
  "dynamic_partition.start" = "-${PARTITION_KEEP_DAYS}",
  "dynamic_partition.end" = "${PARTITION_AHEAD_DAYS}",
  "dynamic_partition.prefix" = "p",
  "dynamic_partition.create_history_partition" = "false"
);
SQL

echo "wrote $SQL_FILE (${DATABASE}.${TABLE}, ${BUCKETS} buckets, replication ${REPLICATION_NUM}, keep ${PARTITION_KEEP_DAYS}d / ahead ${PARTITION_AHEAD_DAYS}d)"
[ "$DRY_RUN" = 1 ] && exit 0

# mysql 9 client cannot authenticate against Doris (mysql_native_password); use the pymysql helper
# from the project-local venv (created on first run).
PY=$(./ensure-venv.sh)
echo "creating ${DATABASE}.${TABLE} on ${VELODB_HOST}:${VELODB_MYSQL_PORT} ..."
"$PY" doris_sql.py --env "$ENV_FILE" -q "$SQL_FILE"
"$PY" doris_sql.py --env "$ENV_FILE" -q -G -e "SHOW CREATE TABLE ${DATABASE}.${TABLE}" | sed -n '/CREATE TABLE/,$p'
echo "ok"
